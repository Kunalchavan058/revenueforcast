"use client";

import { Component, lazy, Suspense, useMemo, type ReactNode } from "react";
import { Card } from "@/components/ui/card";
import { Skeleton } from "@/components/ui/skeleton";
import { salesPointsSchema, type SalesPoint } from "@/components/charts/types";
import { formatDate, formatSales } from "@/lib/format";
import { EmptyState } from "./empty-state";
import { ErrorBanner } from "./error-banner";

const SalesChart = lazy(() => import("@/components/charts/sales-chart"));

/** Contain renderer/import failures without hiding the surrounding source metadata. */
class ChartBoundary extends Component<
  { children: ReactNode },
  { failed: boolean }
> {
  state = { failed: false };
  static getDerivedStateFromError(): { failed: boolean } {
    return { failed: true };
  }
  render(): ReactNode {
    return this.state.failed ? (
      <ErrorBanner
        title="Chart unavailable"
        message="The chart renderer could not start. The data table remains available below."
        onRetry={() => this.setState({ failed: false })}
      />
    ) : (
      this.props.children
    );
  }
}

/** Chart states share a stable surface, explicit series labels, and a keyboard-readable data table. */
export function ChartShell({
  title,
  description,
  points = [],
  loading = false,
  lastObservedDate,
  showPredictions = true,
  error,
  onRetry,
  emptyTitle = "No forecast to display",
  emptyDescription = "The forecast workspace is being prepared. No predictions have been generated by this page.",
}: {
  title: string;
  description: string;
  points?: readonly SalesPoint[];
  loading?: boolean;
  lastObservedDate?: string;
  showPredictions?: boolean;
  error?: string;
  onRetry?: () => void;
  emptyTitle?: string;
  emptyDescription?: string;
}): React.JSX.Element {
  const parsed = useMemo(() => salesPointsSchema.safeParse(points), [points]);
  const ordered = useMemo(
    () =>
      parsed.success
        ? [...parsed.data].sort((a, b) => a.date.localeCompare(b.date))
        : [],
    [parsed],
  );
  const hasValues = ordered.some(
    (point) => point.actual !== null || point.predicted !== null,
  );
  return (
    <Card className="overflow-hidden">
      <div className="flex flex-wrap items-start justify-between gap-4 border-b border-border p-6">
        <div>
          <h2 className="text-base font-semibold">{title}</h2>
          <p className="mt-1 text-xs leading-5 text-muted-foreground">
            {description}
          </p>
        </div>
        <div
          className="flex flex-wrap gap-4 text-xs text-muted-foreground"
          aria-label="Chart legend"
        >
          <span className="inline-flex items-center gap-2">
            <span
              aria-hidden="true"
              className="w-5 border-t-2 border-primary"
            />
            Historical actuals
          </span>
          {showPredictions && (
            <span className="inline-flex items-center gap-2">
              <span
                aria-hidden="true"
                className="w-5 border-t-2 border-dashed border-teal"
              />
              Predicted sales
            </span>
          )}
        </div>
      </div>
      {loading ? (
        <div role="status" aria-label="Loading chart" className="p-6">
          <Skeleton className="h-64 w-full" />
        </div>
      ) : error || !parsed.success ? (
        <div className="p-6">
          <ErrorBanner
            title="Chart data unavailable"
            message={
              error ??
              "Chart rows must contain unique calendar dates and finite nonnegative values."
            }
            onRetry={onRetry}
          />
        </div>
      ) : !hasValues ? (
        <EmptyState title={emptyTitle} description={emptyDescription} />
      ) : (
        <div className="p-4">
          <ChartBoundary>
            <Suspense
              fallback={
                <div role="status" aria-label="Loading chart renderer">
                  <Skeleton className="h-80 w-full" />
                </div>
              }
            >
              <SalesChart
                points={ordered}
                description={description}
                lastObservedDate={lastObservedDate}
              />
            </Suspense>
          </ChartBoundary>
          <details className="mt-4 border-t border-border px-2">
            <summary className="text-sm font-medium">
              View chart data table
            </summary>
            <div
              role="region"
              aria-label={`${title} data table`}
              tabIndex={0}
              className="overflow-x-auto pb-4"
            >
              <table className="w-full text-left text-xs">
                <caption className="sr-only">
                  {title}: source Sales units; missing values are not zero.
                </caption>
                <thead>
                  <tr>
                    <th scope="col" className="p-2">
                      Date
                    </th>
                    <th scope="col" className="p-2">
                      Historical actuals
                    </th>
                    <th scope="col" className="p-2">
                      Predicted sales
                    </th>
                  </tr>
                </thead>
                <tbody>
                  {ordered.map((point) => (
                    <tr key={point.date} className="border-t border-border">
                      <th scope="row" className="p-2 font-normal">
                        {formatDate(point.date)}
                      </th>
                      <td className="p-2 tabular-nums">
                        {formatSales(point.actual)}
                      </td>
                      <td className="p-2 tabular-nums">
                        {formatSales(point.predicted)}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </details>
        </div>
      )}
    </Card>
  );
}
